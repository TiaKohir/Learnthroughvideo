import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { normalizeLesson } from "../src/lesson/schema.ts";

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const CHROME = process.env.BROWSER_EXECUTABLE || "/opt/pw-browsers/chromium-1243/chrome-linux64/chrome";
export const lessonDir = (slug) => join(ROOT, "lessons", slug);
export const readJSON = (p) => JSON.parse(readFileSync(p, "utf8"));
export const writeJSON = (p, v) => writeFileSync(p, JSON.stringify(v, null, 2) + "\n");

export const readScript = (slug) => {
  const p = join(lessonDir(slug), "script.json");
  if (!existsSync(p)) throw new Error(`${p} not found — run: npm run lesson -- plan ${slug}`);
  return normalizeLesson(readJSON(p));
};

export const readArticle = (slug) => {
  const dir = lessonDir(slug);
  for (const name of ["article.md", "article.txt"]) if (existsSync(join(dir, name))) return readFileSync(join(dir, name), "utf8");
  throw new Error(`No article.md in ${dir}`);
};

/** Writes src/generated/{lesson.json,custom.tsx} so the Remotion composition renders this lesson. */
export const prepare = (slug) => {
  const lesson = readScript(slug);
  const timingPath = join(lessonDir(slug), "timing.json");
  if (!existsSync(timingPath)) throw new Error(`${timingPath} not found — run: npm run lesson -- audio ${slug}`);
  const timing = readJSON(timingPath);
  const gen = join(ROOT, "src/generated");
  mkdirSync(gen, { recursive: true });
  writeJSON(join(gen, "lesson.json"), { slug, lesson, timing });
  const hasCustom = existsSync(join(lessonDir(slug), "scenes.tsx"));
  writeFileSync(
    join(gen, "custom.tsx"),
    hasCustom
      ? `// generated by scripts/lesson.mjs prepare ${slug}\nimport scenes from "../../lessons/${slug}/scenes";\nexport const customScenes = scenes;\n`
      : `// generated by scripts/lesson.mjs prepare ${slug}\nimport type React from "react";\nexport const customScenes: Record<string, React.FC> = {};\n`,
  );
  return { lesson, timing, hasCustom };
};
